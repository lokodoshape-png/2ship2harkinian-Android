const char* Tr(const char* text) {
    if (text == nullptr || text[0] == '\0' ||
        CVarGetInteger(CVAR_MENU_LANGUAGE, MENU_LANGUAGE_PORTUGUESE_BR) != MENU_LANGUAGE_PORTUGUESE_BR) {
        return text;
    }

    const char* idStart = strstr(text, "##");
    if (idStart == nullptr) {
        auto found = sPortuguese.find(text);
        return found != sPortuguese.end() ? found->second : text;
    }

    // Translated label + the original "##id" part, built once per label.
    static std::unordered_map<std::string, std::string> sWithId;
    auto cached = sWithId.find(text);
    if (cached != sWithId.end()) {
        return cached->second.c_str();
    }
    auto found = sPortuguese.find(std::string(text, idStart - text));
    if (found == sPortuguese.end()) {
        return text;
    }
    return sWithId.emplace(text, std::string(found->second) + idStart).first->second.c_str();
}

std::string Tr(const std::string& text) {
    return Tr(text.c_str());
}

